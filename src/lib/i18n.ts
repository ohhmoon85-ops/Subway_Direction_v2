export function t(lang: Lang, key: MessageKey, vars: Record<string, string | number> = {}): string {
  // "1번째 역"은 "다음 역"으로 (기획서 10장 고칠 점 2)
  if (key === 'nth' && Number(vars.n) === 1) return t(lang, 'nthNext');
  const one = Number(vars.n) === 1 ? ONE[lang]?.[key] : undefined;
  let s = one ?? MESSAGES[lang][key] ?? MESSAGES.ko[key];
  if (key === 'nth' && lang === 'en') vars = { ...vars, ord: ordinalEn(Number(vars.n)) };
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** 노선 배지 글자: 한국어 화면은 "수인분당", 외국어 화면은 "SB" (한글이 남지 않게) */
export function badgeText(lang: Lang, line: { num: string; abbr?: string }): string {
  return lang === 'ko' ? line.num : (line.abbr ?? line.num);
}

/** 문장 속 역 이름: '시청' → '시청역', 'City Hall' → 'City Hall Station' */
export function withStation(lang: Lang, name: string): string {
  switch (lang) {
    case 'ko':
      return name.endsWith('역') ? name : `${name}역`;
    case 'en':
      return /station$/i.test(name) ? name : `${name} Station`;
    default:
      // 외국어 화면의 역명은 영어 표기(name_en) 그대로 — "Seoul駅"처럼 글자가 섞이지 않게
      return name;
  }
}

/** 목록을 언어에 맞게 잇는다 */
export function joinNames(lang: Lang, names: string[]): string {
  const sep = lang === 'ko' || lang === 'en' || lang === 'es' || lang === 'fr' ? ', ' : '・';
  return names.join(lang === 'zh' || lang === 'zh-TW' ? '、' : sep);
}

/** 언어 태그 하나 → 지원 언어 (중국어는 번체 지역·스크립트면 zh-TW) */
export function langFromTag(tag: string): Lang | null {
  const t0 = tag.trim().toLowerCase();
  if (!t0) return null;
  if (t0.startsWith('zh')) return /hant|-tw|-hk|-mo/.test(t0) ? 'zh-TW' : 'zh';
  const base = t0.split('-')[0];
  return isLang(base) ? base : null;
}

/** 휴대폰 언어 목록(navigator.languages) → 첫 번째로 지원하는 언어, 없으면 영어 */
export function langFromList(tags: readonly string[] | undefined): Lang {
  for (const tag of tags ?? []) {
    const l = langFromTag(tag);
    if (l) return l;
  }
  return 'en';
}

export function isLang(x: unknown): x is Lang {
  return typeof x === 'string' && (LANGS as readonly string[]).includes(x);
}

/** Accept-Language 또는 navigator.language → 지원 언어 */
export function pickLang(header: string | null | undefined): Lang {
  if (!header) return 'ko';
  const parts = header
    .split(',')
    .map((p) => {
      const [tag, q] = p.trim().split(';q=');
      return { tag: tag.toLowerCase(), q: q ? Number(q) : 1 };
    })
    .sort((a, b) => b.q - a.q);
  return langFromList(parts.map((p) => p.tag));
}
